/**
 * These are convenience functions to make working with moods easier
 */
export const moodDB = {
  /**
   * Add a new mood entry
   *
   * Usage:
   * await moodDB.add({ level: 'high', timestamp: new Date() })
   *
   * What happens:
   * 1. Dexie auto-generates an 'id' (1, 2, 3, etc.)
   * 2. Saves to IndexedDB on user's device
   * 3. Returns the generated id
   */

  async add(mood: Omit<MoodEntry, "id">) {
    // 'Omit<MoodEntry, 'id'>' means "all MoodEntry fields EXCEPT id"
    // Because Dexie auto-generates the id
    return await db.moods.add({
      ...mood,
      createdAt: new Date(),
      synced: false,
    });
  },

  async getLatest(): Promise<MoodEntry | undefined> {
    return await db.moods.orderBy("createdAt").reverse().first();
  },

  async getToday(): Promise<MoodEntry | undefined> {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const tomorrow = new Date(today);
    tomorrow.setDate(tomorrow.getDate() + 1);

    return await db.moods
      .where("createdAt")
      .between(today, tomorrow, true, false)
      .first();
  },

  async getTodayMoods(): Promise<MoodEntry[]> {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const tomorrow = new Date(today);
    tomorrow.setDate(tomorrow.getDate() + 1);

    return await db.moods
      .where("createdAt")
      .between(today, tomorrow, true, false)
      .toArray();
  },

  /**
   * Get all moods that haven't been synced to Supabase yet
   *
   * This is used when internet comes back online
   */
  async getUnsynced(): Promise<MoodEntry[]> {
    return await db.moods.filter((mood) => mood.synced === false).toArray();
  },

  /**
   * Mark a mood as synced after successfully sending to Supabase
   */
  async markAsSynced(id: number): Promise<number> {
    return await db.moods.update(id, { synced: true });
  },

  /**
   * Get all moods (for analytics)
   */
  async getAll(): Promise<MoodEntry[]> {
    return await db.moods.toArray();
  },
};

