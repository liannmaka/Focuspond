export const taskDB = {
  /**
   * Add a new task
   *
   * Usage:
   * await taskDB.add({
   *   title: 'Write proposal',
   *   energyRequired: 'high',
   *   priority: 'high',
   *   estimatedMinutes: 60,
   *   isFrogTask: true,
   *   completed: false,
   *   createdAt: new Date()
   * });
   */

  async add(task: Omit<Task, "id">): Promise<number> {
    const pomodoroCount = Math.ceil(task.estimatedMinutes / 25);
    return await db.tasks.add({
      ...task,
      pomodoroCount,
      pomodorosCompleted: 0,
      synced: false,
    });
  },

  /**
   * Get all incomplete tasks
   */
  async getIncomplete(): Promise<Task[]> {
    return await db.tasks.filter((task) => task.completed === false).toArray();
  },

  /**
   * Get all frog tasks (incomplete)
   */
  async getFrogTasks(): Promise<Task[]> {
    return await db.tasks
      .filter((task) => task.isFrogTask === true && task.completed === false)
      .toArray();
  },

  /**
   * Get tasks by energy level
   */
  async getByEnergy(energy: EnergyLevel): Promise<Task[]> {
    return await db.tasks
      .where("energyRequired")
      .equals(energy)
      .filter((task) => task.completed === false)
      .toArray();
  },

  /**
   * Mark task as complete
   */
  async complete(id: number): Promise<number> {
    return await db.tasks.update(id, {
      completed: true,
      completedAt: new Date(),
      synced: false, // Need to sync this change
    });
  },

  /**
   * Toggle frog task status
   */
  async toggleFrogTask(id: number, isFrog: boolean): Promise<number> {
    return await db.tasks.update(id, {
      isFrogTask: isFrog,
      synced: false,
    });
  },

  /**
   * Update task (general purpose)
   */
  async update(id: number, updates: Partial<Task>): Promise<number> {
    return await db.tasks.update(id, {
      ...updates,
      synced: false, // Mark as needing sync
    });
  },

  /**
   * Get unsynced tasks
   */

  async getUnsynced(): Promise<Task[]> {
    return await db.tasks.filter((task) => task.synced === false).toArray();
  },

  /**
   * Mark as synced
   */
  async markAsSynced(id: number): Promise<number> {
    return await db.tasks.update(id, { synced: true });
  },

  /**
   * Get all tasks
   */
  async getAll(): Promise<Task[]> {
    return await db.tasks.toArray();
  },

  /**
   * Delete a task
   */
  async delete(id: number): Promise<void> {
    await db.tasks.delete(id);
  },
};

