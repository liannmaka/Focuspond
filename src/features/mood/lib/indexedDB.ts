export interface MoodEntry {
  id?: number; // Dexie auto-generates it
  level: MoodLevel;
  label: string;
  note?: string; // Optional: 'user_skipped', 'onboarding_flow'
  energyLevel: EnergyLevel;
  createdAt?: Date;
  synced?: boolean; // Has this been sent to Supabase? (false = pending)
}
export interface Task {
  id?: number; // Auto-generated by Dexie
  title: string;
  description?: string;

  // Energy matching (for mood-based suggestions)
  energyRequired: EnergyLevel; // 'high' | 'medium' | 'low'

  // Priority & time
  priority: "high" | "medium" | "low";
  estimatedMinutes: number; // How long user thinks it'll take (15, 30, 60, etc.)

  // Pomodoro tracking
  pomodoroCount?: number; // How many pomodoros user allocated (auto-calculated from estimatedMinutes)
  pomodorosCompleted?: number; // How many pomodoros done so far (0 initially)

  // Frog task
  isFrogTask: boolean; // Is this the "eat the frog" task?

  // Status
  completed: boolean; // false initially, true when done
  createdAt: Date; // When task was created
  completedAt?: Date; // When task was marked complete (undefined until done)

  // Sync with backend
  synced?: boolean; // false = needs to sync to Supabase, true = already synced
}

export interface PomodoroSession {
  id?: number;
  taskId?: number; // Optional: can be linked to a task or standalone
  startTime: Date;
  endTime?: Date; // undefined if session is still running
  duration: number; // In minutes (25, 15, 50, etc.)
  completed: boolean; // Did they complete the full session?
  mood?: MoodLevel; // Optional: their mood during this session
  synced?: boolean;
}

export class FocusPondDB extends Dexie {
  // Define tables (like tables in SQL)
  moods!: Table<MoodEntry, number>; // Table name: 'moods', Primary key type: number
  tasks!: Table<Task, number>;
  pomodoros!: Table<PomodoroSession, number>;

  constructor() {
    super("FocusPondDB"); // Database name (stored as 'FocusPondDB' in browser)

    /**
     * Define database schema (structure)
     *
     * The string syntax:
     * '++id' = Auto-incrementing primary key
     * 'level' = Create index on this field (for faster queries)
     * 'timestamp' = Create index on this field
     * 'synced' = Create index on this field
     *
     * Indexes allow fast queries like:
     * - db.moods.where('level').equals('high')
     * - db.moods.where('synced').equals(false)
     */
    this.version(1).stores({
      moods: "++id, level, createdAt",
      tasks: "++id, priority, energyRequired, createdAt",
      pomodoros: "++id, taskId, startTime",
    });
  }
}

